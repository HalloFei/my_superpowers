import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

KB = Path(__file__).resolve().parent.parent / "scripts" / "kb.py"
PY = sys.executable

M_A_START = "<!-- kb:active:start (generated by kb index; status column is authoritative) -->"
M_A_END = "<!-- kb:active:end -->"
M_R_START = "<!-- kb:archive:start (generated by kb index; content frozen, sha256 enforced) -->"
M_R_END = "<!-- kb:archive:end -->"

CONFIG = """schema_version: 1
types:
  specs: docs/specs
  plans: docs/plans
  decisions: docs/decisions
archive: docs/archive
index: docs/INDEX.md
archive_index: docs/archive/INDEX.md
root_files: []
"""

CONFIG_PLAIN = """schema_version: 1
types:
  specs: docs/specs
  plans: docs/plans
archive: docs/archive
index: docs/INDEX.md
archive_index: docs/archive/INDEX.md
root_files: []
"""

SPEC_NA = "# spec\n\n**Decision:** N/A — bounded change, no ADR\n"
PLAN_NA = "# plan\n\n**Spec:** N/A — bounded change, no spec\n"


def run(*args, cwd=None):
    return subprocess.run([PY, str(KB)] + [str(a) for a in args],
                          capture_output=True, text=True, cwd=cwd)


def make_ws(tmp, files, config=CONFIG):
    root = Path(tmp)
    for d in ("docs/specs", "docs/plans", "docs/decisions", "docs/archive/decisions"):
        (root / d).mkdir(parents=True, exist_ok=True)
    (root / "docs" / "kb.yaml").write_text(config, encoding="utf-8")
    (root / "docs" / "INDEX.md").write_text("# idx\n\n" + M_A_START + "\n" + M_A_END + "\n", encoding="utf-8")
    (root / "docs" / "archive" / "INDEX.md").write_text("# arch\n\n" + M_R_START + "\n" + M_R_END + "\n", encoding="utf-8")
    base = {
        "docs/specs/base.md": SPEC_NA,
        "docs/plans/base.md": PLAN_NA,
    }
    base.update(files)
    for rel, text in base.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    return root


def adr(topic, extra=""):
    return "# ADR\n\n**Topic:** " + topic + "\n" + extra


class DecisionsTest(unittest.TestCase):
    def test_adr_defaults_active(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/decisions/0001-first.md": adr("bucketing")})
            self.assertEqual(run("index", "--root", root).returncode, 0)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 0, r.stdout)
            self.assertRegex((root / "docs/INDEX.md").read_text(encoding="utf-8"),
                             r"docs/decisions/0001-first\.md \| decisions \| active")

    def test_bad_adr_filename(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/decisions/1-first.md": adr("bucketing")})
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("filename", r.stdout)

    def test_duplicate_adr_id(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {
                "docs/decisions/0001-first.md": adr("bucketing"),
                "docs/archive/decisions/0001-old.md": "# old ADR\n",
            })
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("duplicate ADR id", r.stdout)

    def test_topic_required(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/decisions/0001-first.md": "# ADR\n"})
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("missing Topic", r.stdout)

    def test_topic_unique(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {
                "docs/decisions/0001-a.md": adr("bucketing"),
                "docs/decisions/0002-b.md": adr("bucketing"),
            })
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("topic 'bucketing' has 2 active ADRs", r.stdout)

    def test_topic_multi(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {
                "docs/decisions/0001-a.md": adr("bucketing, canvas"),
                "docs/decisions/0002-b.md": adr("canvas"),
            })
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            (root / "docs/decisions/0002-b.md").write_text(adr("gateway"), encoding="utf-8")
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 0, r.stdout)

    def test_duplicate_field(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/decisions/0001-a.md": adr("bucketing", "**Topic:** gateway\n")})
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("duplicate field", r.stdout)

    def test_non_opted_workspace_unaffected(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {
                "docs/specs/a.md": "# a\n",
                "docs/plans/b.md": "# b\n",
            }, config=CONFIG_PLAIN)
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 0, r.stdout)

    def test_decision_points_to_archived(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {
                "docs/decisions/0001-a.md": adr("old-topic"),
                "docs/decisions/0002-b.md": adr("new-topic"),
                "docs/specs/s.md": "# s\n\n**Decision:** ADR-0001\n",
            })
            run("index", "--root", root)
            r = run("archive", "docs/decisions/0001-a.md", "--superseded-by", "ADR-0002", "--root", root)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("is archived", r.stdout)
            self.assertIn("ADR-0002", r.stdout)

    def test_decision_field_required(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/specs/s.md": "# s\n"})
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("missing Decision", r.stdout)

    def test_na_requires_reason(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/specs/s.md": "# s\n\n**Decision:** N/A\n"})
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("N/A requires a reason", r.stdout)

    def test_na_with_reason_ok(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {})
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 0, r.stdout)

    def test_duplicate_decision_id(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {
                "docs/decisions/0001-a.md": adr("bucketing"),
                "docs/specs/s.md": "# s\n\n**Decision:** ADR-0001, ADR-0001\n",
            })
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("duplicate ADR in Decision", r.stdout)

    def test_spec_binding_archived(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {
                "docs/specs/old.md": SPEC_NA,
                "docs/plans/p.md": "# p\n\n**Spec:** docs/archive/specs/old.md\n",
            })
            run("index", "--root", root)
            run("archive", "docs/specs/old.md", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("is not active", r.stdout)

    def test_spec_binding_draft(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {
                "docs/specs/draft.md": SPEC_NA,
                "docs/plans/p.md": "# p\n\n**Spec:** docs/specs/draft.md\n",
            })
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("is not active", r.stdout)

    def test_spec_field_required(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/plans/p.md": "# p\n"})
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("missing Spec", r.stdout)

