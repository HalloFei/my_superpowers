import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

KB = Path(__file__).resolve().parent.parent / "scripts" / "kb.py"
PY = sys.executable

M_A_START = "<!-- kb:active:start (generated by kb index; status column is authoritative) -->"
M_A_END = "<!-- kb:active:end -->"
M_R_START = "<!-- kb:archive:start (generated by kb index; content frozen, sha256 enforced) -->"
M_R_END = "<!-- kb:archive:end -->"

CONFIG = """schema_version: 1
types:
  specs: docs/specs
  plans: docs/plans
archive: docs/archive
index: docs/INDEX.md
archive_index: docs/archive/INDEX.md
root_files: []
"""


def run(*args, cwd=None):
    return subprocess.run([PY, str(KB)] + [str(a) for a in args],
                          capture_output=True, text=True, cwd=cwd)


def make_ws(tmp, files):
    root = Path(tmp)
    (root / "docs" / "specs").mkdir(parents=True)
    (root / "docs" / "plans").mkdir(parents=True)
    (root / "docs" / "archive" / "specs").mkdir(parents=True)
    (root / "docs" / "kb.yaml").write_text(CONFIG, encoding="utf-8")
    (root / "docs" / "INDEX.md").write_text("# idx\n\n" + M_A_START + "\n" + M_A_END + "\n", encoding="utf-8")
    (root / "docs" / "archive" / "INDEX.md").write_text("# arch\n\n" + M_R_START + "\n" + M_R_END + "\n", encoding="utf-8")
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    return root


class KbTest(unittest.TestCase):
    def test_index_defaults_and_check_ok(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {
                "docs/specs/a.md": "# a\n",
                "docs/plans/b.md": "# b\n",
                "docs/archive/specs/old.md": "# old\n",
            })
            r = run("index", "--root", root)
            self.assertEqual(r.returncode, 0, r.stderr)
            self.assertIn("2 active, 1 archived", r.stdout)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            r = run("status", "docs/specs/a.md", "--root", root)
            self.assertIn("draft", r.stdout)
            r = run("status", "docs/plans/b.md", "--root", root)
            self.assertIn("active", r.stdout)
            r = run("status", "docs/archive/specs/old.md", "--root", root)
            self.assertIn("archived", r.stdout)

    def test_missing_index_row_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/specs/a.md": "# a\n"})
            run("index", "--root", root)
            (root / "docs/specs/c.md").write_text("# c\n", encoding="utf-8")
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("missing from active index", r.stdout)

    def test_frozen_archive_sha256(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/archive/specs/old.md": "# old\n"})
            run("index", "--root", root)
            (root / "docs/archive/specs/old.md").write_text("# old changed\n", encoding="utf-8")
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("frozen archive changed", r.stdout)

    def test_illegal_transition_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/plans/b.md": "# b\n"})
            run("index", "--root", root)
            run("set-status", "docs/plans/b.md", "final", "--root", root)
            r = run("set-status", "docs/plans/b.md", "active", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("illegal transition", r.stdout)

    def test_unknown_status_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/specs/a.md": "# a\n"})
            run("index", "--root", root)
            r = run("set-status", "docs/specs/a.md", "done", "--root", root)
            self.assertEqual(r.returncode, 2, r.stdout)

    def test_final_not_allowed_for_specs(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/specs/a.md": "# a\n"})
            run("index", "--root", root)
            run("set-status", "docs/specs/a.md", "active", "--root", root)
            r = run("set-status", "docs/specs/a.md", "final", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)

    def test_inline_map_config(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "docs").mkdir()
            (root / "docs" / "kb.yaml").write_text(
                "types: {specs: docs/specs}\narchive: docs/archive\nindex: docs/INDEX.md\narchive_index: docs/archive/INDEX.md\n",
                encoding="utf-8")
            (root / "docs" / "INDEX.md").write_text(M_A_START + "\n" + M_A_END + "\n", encoding="utf-8")
            (root / "docs" / "archive").mkdir()
            (root / "docs" / "archive" / "INDEX.md").write_text(M_R_START + "\n" + M_R_END + "\n", encoding="utf-8")
            r = run("index", "--root", root)
            self.assertEqual(r.returncode, 0, r.stderr)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 0, r.stdout)

    def test_broken_link_detected(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/specs/a.md": "see docs/specs/nope.md\n"})
            run("index", "--root", root)
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 1, r.stdout)
            self.assertIn("broken link", r.stdout)

    def test_archive_command_moves_and_records(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/specs/a.md": "# a\n", "docs/specs/new.md": "# new\n"})
            run("index", "--root", root)
            r = run("archive", "docs/specs/a.md", "--superseded-by", "docs/specs/new.md", "--root", root)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            self.assertFalse((root / "docs/specs/a.md").exists())
            self.assertTrue((root / "docs/archive/specs/a.md").exists())
            self.assertIn("superseded", (root / "docs/archive/INDEX.md").read_text(encoding="utf-8"))
            r = run("check", "--root", root)
            self.assertEqual(r.returncode, 0, r.stdout)

    def test_hook_install(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = make_ws(tmp, {"docs/specs/a.md": "# a\n"})
            run("index", "--root", root)
            subprocess.run(["git", "init"], cwd=root, capture_output=True, text=True)
            r = run("hook", "--install", "--root", root)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            hook = root / ".git" / "hooks" / "pre-commit"
            self.assertTrue(hook.exists())
            self.assertIn("installed by kb", hook.read_text(encoding="utf-8"))


if __name__ == "__main__":
    unittest.main()
